package com.quantumtemplates

import com.intellij.openapi.application.runReadActionBlocking
import com.intellij.openapi.editor.Editor
import com.intellij.openapi.fileEditor.FileDocumentManager
import com.intellij.openapi.fileEditor.OpenFileDescriptor
import com.intellij.openapi.project.Project
import com.intellij.openapi.vfs.VirtualFile
import com.intellij.psi.search.FilenameIndex
import com.intellij.psi.search.GlobalSearchScope
import java.awt.event.InputEvent
import java.awt.event.MouseEvent

/** A declaration found in a .qtn file. [line] is zero-based. */
data class QtnDeclaration(val word: String, val file: VirtualFile, val line: Int) {
    fun navigate(project: Project) = OpenFileDescriptor(project, file, line, 0).navigate(true)
}

// Maps a symbol generated by the Quantum codegen (GravityOrientation, QPrototypeGravityOrientation,
// GravityOrientationPrototype, ISignalOnFoo, EventFoo, Input...) back to its declaration in a .qtn file.
// Matching is by name only: the codegen leaves no source mapping in the generated C#.
object QtnLookup {

    /** The editor offset an action targets: under the pointer for a mouse shortcut, otherwise the caret. */
    fun targetOffset(editor: Editor, inputEvent: InputEvent?): Int =
        (inputEvent as? MouseEvent)
            ?.takeIf { it.component == editor.contentComponent }
            ?.let { editor.logicalPositionToOffset(editor.xyToLogicalPosition(it.point)) }
            ?: editor.caretModel.offset

    fun identifierAt(text: CharSequence, offset: Int): String? {
        fun isIdent(c: Char) = c.isLetterOrDigit() || c == '_'
        var start = offset.coerceIn(0, text.length)
        var end = start
        while (start > 0 && isIdent(text[start - 1])) start--
        while (end < text.length && isIdent(text[end])) end++
        return if (start < end) text.substring(start, end) else null
    }

    /** Must not be called while indexing (see DumbService). */
    fun find(project: Project, word: String): QtnDeclaration? = runReadActionBlocking {
        findDeclaration(project, word, candidateNames(word))
    }

    /** The QTN names a generated symbol may have come from, most specific first. */
    private fun candidateNames(word: String): List<String> {
        val names = mutableListOf(word)
        fun stripped(prefix: String = "", suffix: String = "") {
            if (word.length > prefix.length + suffix.length && word.startsWith(prefix) && word.endsWith(suffix)) {
                names.add(word.substring(prefix.length, word.length - suffix.length))
            }
        }
        stripped(prefix = "QPrototype")   // Unity wrapper:   QPrototypeFoo  -> component Foo
        stripped(suffix = "Prototype")    // prototype:       FooPrototype   -> component Foo
        stripped(prefix = "ISignal")      // signal interface: ISignalOnFoo  -> signal OnFoo
        stripped(prefix = "Event")        // event class:     EventFoo       -> event Foo
        return names.distinct()
    }

    private fun findDeclaration(project: Project, word: String, names: List<String>): QtnDeclaration? {
        val files = FilenameIndex.getAllFilesByExt(project, "qtn", GlobalSearchScope.projectScope(project))
            .sortedBy { it.path }
        if (files.isEmpty()) return null
        val texts = files.map { file ->
            // Use the open document when there is one so unsaved edits are searched too.
            file to (FileDocumentManager.getInstance().getCachedDocument(file)?.charsSequence?.toString()
                ?: String(file.contentsToByteArray(), file.charset))
        }

        // Prefer the most specific name across all files before falling back to looser ones.
        for (pattern in names.map(::declarationPattern)) {
            for ((file, text) in texts) {
                text.lineSequence().forEachIndexed { line, content ->
                    if (pattern.containsMatchIn(content)) return QtnDeclaration(word, file, line)
                }
            }
        }
        return null
    }

    private fun declarationPattern(name: String): Regex {
        // `input { ... }` has no name of its own; it generates Quantum.Input.
        if (name == "Input") return Regex("""^\s*input\b""")
        // Allows leading modifiers such as `singleton component`, `synced event` or `abstract event`,
        // and `bitset[256] Foo`.
        return Regex(
            """^\s*(?:\w+\s+)*(?:component|struct|enum|flags|union|asset|event|signal|bitset\s*\[\s*\w+\s*\])\s+""" +
                Regex.escape(name) + """\b"""
        )
    }
}
